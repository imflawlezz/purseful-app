function getNestedValue(obj: any, path: string): string {
  return path.split('.').reduce((current, key) => current?.[key], obj) || path;
}

function pluralize(count: number, locale: Locale, key: string): string {
  if (locale === 'en') {
    return count === 1 ? 'account' : 'accounts';
  } else if (locale === 'pl') {
    if (count === 1) return 'konto';
    if (count >= 2 && count <= 4) return 'konta';
    return 'kont';
  } else if (locale === 'ru') {
    const lastDigit = count % 10;
    const lastTwoDigits = count % 100;
    if (lastTwoDigits >= 11 && lastTwoDigits <= 19) return 'счетов';
    if (lastDigit === 1) return 'счет';
    if (lastDigit >= 2 && lastDigit <= 4) return 'счета';
    return 'счетов';
  }
  return count === 1 ? 'account' : 'accounts';
}

export function t(key: string, locale: Locale = 'en', params?: Record<string, any>): string {
  const translation = getNestedValue(translations[locale], key) || getNestedValue(translations.en, key) || key;
  
  if (params) {
    let result = translation;
    
    // Handle plural form if {plural} placeholder exists and count is provided
    if (result.includes('{plural}') && typeof params.count === 'number') {
      const pluralForm = pluralize(params.count, locale, key);
      result = result.replace(/\{plural\}/g, pluralForm);
    }
    
    // Replace all other parameters
    Object.entries(params).forEach(([paramKey, paramValue]) => {
      if (paramKey === 'plural') {
        // Skip, already handled above
        return;
      } else if (typeof paramValue === 'number' && result.includes(`{${paramKey}, plural`)) {
        // Simple pluralization (legacy format)
        const match = result.match(/\{(\w+), plural, ([^}]+)\}/);
        if (match) {
          const pluralForm = pluralize(paramValue, locale, paramKey);
          result = result.replace(match[0], `${paramValue} ${pluralForm}`);
        }
      } else {
        result = result.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramValue));
      }
    });
    return result;
  }
  
  return translation;
}

export function getCategoryName(category: Category, locale: Locale = 'en'): string {
  // Check if it's a default category (has known ID pattern)
  if (category.id.startsWith('income-') || category.id.startsWith('expense-')) {
    const translated = t(`defaultCategories.${category.id}`, locale);
    if (translated !== `defaultCategories.${category.id}`) {
      return translated;
    }
  }
  // Return custom category name as-is
  return category.name;
}

